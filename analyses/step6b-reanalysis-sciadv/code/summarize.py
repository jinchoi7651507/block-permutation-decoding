"""Summary tables and the pre-specified verdict sentences (DESIGN.md section 6) from OUT/gate.json and OUT/tests.json.

  python summarize.py [--out OUT]   -> prints Markdown; writes OUT/SUMMARY.md
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

ALPHA = 0.05
DEFAULT_OUT = Path(__file__).resolve().parents[1] / "out"


DRIFT_MAX = 60.0      # percent; DESIGN.md section 0 item 3 (both windows since 2026-11-08)


def verdict(window, p_trial, p_block, drift_acc=None):
    """Verdict sentence of DESIGN.md 4.5, generated from the group p values and the drift accuracy (both windows)."""
    drift_ok = drift_acc is not None and not math.isnan(drift_acc)
    t = "above chance" if p_trial < ALPHA else "not above chance"
    if p_block < ALPHA:
        b = "it is above the block-arrangement null (p = %.3g)" % p_block
    elif drift_ok and drift_acc >= DRIFT_MAX:
        b = "the result is uninformative under drift (same-condition first-vs-last accuracy %.1f %%; p = %.3g)" % (
            drift_acc, p_block)
        if window == "PERI":
            b += " (drift accuracy measured in the ITI window)"
    elif p_trial < ALPHA:
        b = ("the decoding is not distinguishable from what the block arrangement alone gives (p = %.3g)" % p_block)
    else:
        b = "it is not above the block-arrangement null (p = %.3g)" % p_block
    if not drift_ok:
        b += " (drift check not available)"
    return ("%s window: under the trial-label shuffle, group-level context decoding is %s (p = %.3g); under the "
            "block test, %s. The block test rests on an exchangeability model because the block order was fixed."
            % (window, t, p_trial, b))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    a = ap.parse_args()
    out = Path(a.out)
    g = json.load(open(out / "gate.json"))
    L = ["# Reanalysis summary (generated by code/summarize.py)", "", "## Reproduction gate: %s" % g["status"], ""]
    L += ["| item | value | expected | ok |", "|---|---|---|---|"]
    for k, v in g["items"].items():
        L.append("| %s | %s | %s | %s |" % (k, json.dumps(v["value"])[:120], v["expected"], v["ok"]))
    if g["status"] != "pass":
        L += ["", "The gate failed; no test is interpreted (DESIGN.md section 3)."]
    else:
        t = json.load(open(out / "tests.json"))
        for w in ("ITI", "PERI"):
            L += ["", "## %s window" % w, "", "| mouse | cells | trials self/cued | accuracy (%) | trial-shuffle p | "
                  "block p (min) | block rank |", "|---|---|---|---|---|---|---|"]
            for r in t["mice"]:
                b, tr = r["windows"][w]["block"], r["windows"][w]["trial"]
                rank = 1 + sum(x > b["observed"] + 1e-9 for x in set(b["null"]))
                L.append("| %d | %d | %d/%d | %.2f | %.3g | %.3g (%.2g) | %d of %d |" % (
                    r["mouse"] + 1, r["n_cells"], r["n_trials"]["self"], r["n_trials"]["cued"], b["observed"], tr["p"],
                    b["p"], b["p_min"], rank, b["n_distinct"]))
            G = t["group"][w]
            L += ["", "Group: mean accuracy %.2f; trial-shuffle p = %.3g; block test p = %.3g (smallest possible %.2g); "
                  "mice at the top arrangement %d of %d (binomial p = %.3g)." % (
                      G["block"]["T"], G["trial"]["p"], G["block"]["p"], G["block"]["p_min"],
                      G["block_top_count"]["k"], G["block_top_count"]["n"], G["block_top_count"]["p"]),
                  "", verdict(w, G["trial"]["p"], G["block"]["p"],
                              t["group"].get("drift_accuracy"))]
        L += ["", "## Controls", "", "| mouse | movement acc (p) | cued first vs last (p) | self first vs last (p) |",
              "|---|---|---|---|"]
        for r in t["mice"]:
            d = r["drift"]
            f = lambda k: "%.1f (%.3g)" % (d[k]["observed"], d[k]["p"]) if k in d else "n/a"  # noqa: E731
            L.append("| %d | %.1f (%.3g)%s | %s | %s |" % (r["mouse"] + 1, r["movement"]["observed"], r["movement"]["p"],
                                                         " FAILED (flagged)" if r.get("movement_failed") else "",
                                                         f("cued_first_vs_last"), f("self_first_vs_last")))
        L += ["", "Drift accuracy (mean over mice and both same-condition decoders): %s %%" % (
            "n/a" if t["group"].get("drift_accuracy") is None else "%.1f" % t["group"]["drift_accuracy"])]
        L += ["", "## Secondary", ""]
        for k in [k for k in ("S1_ITI", "S1_PERI") if k in t["group"]]:
            L.append("- %s held-out-set accuracy %.2f, block test p = %.3g" % (k, t["group"][k]["T"], t["group"][k]["p"]))
        if "S2_ITI" in t["group"]:
            s2 = t["group"]["S2_ITI"]
            L.append("- S2 ITI-clean trials (%d mice): accuracy %.2f, trial-shuffle p = %.3g, block p = %.3g"
                     % (s2["n_mice"], s2["block"]["T"], s2["trial"]["p"], s2["block"]["p"]))
    txt = "\n".join(L) + "\n"
    (out / "SUMMARY.md").write_text(txt)
    print(txt)


if __name__ == "__main__":
    main()
